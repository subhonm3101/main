create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  category text not null check (char_length(category) between 1 and 80),
  price integer not null check (price between 0 and 1000000),
  weight text not null default '' check (char_length(weight) <= 80),
  description text not null default '' check (char_length(description) <= 1000),
  image_url text not null default '' check (char_length(image_url) <= 2000),
  photo boolean not null default false,
  tag text check (tag is null or char_length(tag) <= 40),
  serving_note text check (serving_note is null or char_length(serving_note) <= 500),
  recipe text check (recipe is null or char_length(recipe) <= 2000),
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  customer_name text not null,
  phone text not null,
  order_type text not null check (order_type in ('Доставка', 'Самовывоз')),
  branch text not null,
  address text,
  comment text,
  total integer not null default 0 check (total between 0 and 1000000),
  status text not null default 'new' check (status in ('new', 'confirmed', 'completed', 'cancelled'))
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders (id) on delete cascade,
  menu_item_id bigint references public.menu_items (id) on delete set null,
  item_name text not null,
  unit_price integer not null check (unit_price between 0 and 1000000),
  quantity integer not null check (quantity between 1 and 9999),
  serving_note text
);
alter table public.order_items add column if not exists serving_note text;

create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_phone_idx on public.orders (phone);
create index if not exists order_items_order_id_idx on public.order_items (order_id);
create index if not exists menu_items_sort_order_idx on public.menu_items (sort_order, id);

create or replace function public.is_donishef_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_donishef_admin() from public;
grant execute on function public.is_donishef_admin() to authenticated;

alter table public.admin_users enable row level security;
alter table public.menu_items enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "Public can read menu" on public.menu_items;
create policy "Public can read menu"
  on public.menu_items for select to anon, authenticated
  using (true);

drop policy if exists "Admins manage menu" on public.menu_items;
create policy "Admins manage menu"
  on public.menu_items for all to authenticated
  using (public.is_donishef_admin())
  with check (public.is_donishef_admin());

drop policy if exists "Admins read orders" on public.orders;
create policy "Admins read orders"
  on public.orders for select to authenticated
  using (public.is_donishef_admin());

drop policy if exists "Admins update orders" on public.orders;
create policy "Admins update orders"
  on public.orders for update to authenticated
  using (public.is_donishef_admin())
  with check (public.is_donishef_admin());

drop policy if exists "Admins read order items" on public.order_items;
create policy "Admins read order items"
  on public.order_items for select to authenticated
  using (public.is_donishef_admin());

revoke all on table public.admin_users, public.menu_items, public.orders, public.order_items from public, anon, authenticated;
revoke all on sequence public.menu_items_id_seq from public, anon, authenticated;
