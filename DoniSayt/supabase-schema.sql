grant select, update on public.orders to authenticated;
grant select on public.order_items to authenticated;
grant usage, select on sequence public.menu_items_id_seq to authenticated;

create or replace function public.create_restaurant_order(
  p_customer_name text,
  p_phone text,
  p_order_type text,
  p_branch text,
  p_address text,
  p_comment text,
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order_id uuid;
  v_line jsonb;
  v_menu_item public.menu_items%rowtype;
  v_item_id bigint;
  v_quantity integer;
  v_total bigint := 0;
  v_line_count integer := 0;
begin
  if char_length(trim(coalesce(p_customer_name, ''))) not between 1 and 120 then
    raise exception 'Укажите имя длиной от 1 до 120 символов.';
  end if;
  if trim(coalesce(p_phone, '')) !~ '^\+?[0-9 ()-]{7,20}$' then
    raise exception 'Укажите корректный номер телефона.';
  end if;
  if p_order_type not in ('Доставка', 'Самовывоз') then
    raise exception 'Неизвестный способ получения заказа.';
  end if;
  if char_length(trim(coalesce(p_branch, ''))) not between 1 and 160 then
    raise exception 'Выберите филиал.';
  end if;
  if p_order_type = 'Доставка' and char_length(trim(coalesce(p_address, ''))) not between 3 and 300 then
    raise exception 'Для доставки укажите адрес.';
  end if;
  if char_length(coalesce(p_comment, '')) > 1000 then
    raise exception 'Комментарий слишком длинный.';
  end if;
  if coalesce(jsonb_typeof(p_items), '') <> 'array' then
    raise exception 'Некорректный список блюд.';
  end if;
  if jsonb_array_length(p_items) not between 1 and 30 then
    raise exception 'В заказе должно быть от 1 до 30 позиций.';
  end if;
  if (
    select count(*)
    from public.orders
    where phone = trim(p_phone)
      and created_at > now() - interval '1 hour'
  ) >= 20 then
    raise exception 'Слишком много заявок с этого номера. Попробуйте позже.';
  end if;

  insert into public.orders (customer_name, phone, order_type, branch, address, comment)
  values (
    trim(p_customer_name),
    trim(p_phone),
    p_order_type,
    trim(p_branch),
    nullif(trim(coalesce(p_address, '')), ''),
    nullif(trim(coalesce(p_comment, '')), '')
  )
  returning id into v_order_id;

  for v_line in select value from jsonb_array_elements(p_items) as lines(value)
  loop
    v_line_count := v_line_count + 1;
    if coalesce(v_line->>'id', '') !~ '^[0-9]{1,18}$'
      or coalesce(v_line->>'quantity', '') !~ '^[0-9]{1,4}$' then
      raise exception 'Некорректная позиция заказа.';
    end if;
    v_item_id := (v_line->>'id')::bigint;
    v_quantity := (v_line->>'quantity')::integer;
    if v_quantity not between 1 and 9999 then
      raise exception 'Некорректное количество позиции.';
    end if;

    select * into v_menu_item
    from public.menu_items
    where id = v_item_id;
    if not found then
      raise exception 'Одно из блюд больше недоступно. Обновите страницу и повторите заказ.';
    end if;

    v_total := v_total + v_menu_item.price::bigint * v_quantity;
    if v_total > 1000000 then
      raise exception 'Сумма заказа превышает допустимый предел.';
    end if;

    insert into public.order_items (order_id, menu_item_id, item_name, unit_price, quantity, serving_note)
    values (
      v_order_id,
      v_menu_item.id,
      v_menu_item.name,
      v_menu_item.price,
      v_quantity,
      coalesce(
        v_menu_item.serving_note,
        case when v_menu_item.category not in ('Напитки', 'Торты', 'Салаты', 'Гарниры', 'Детское меню')
          then 'ЛЕПЁШКА В ПОДАРОК К КАЖДОМУ БЛЮДУ'
          else null
        end
      )
    );
  end loop;

  if v_line_count <> jsonb_array_length(p_items) then
    raise exception 'Некорректное количество позиций заказа.';
  end if;
  update public.orders set total = v_total::integer where id = v_order_id;
  return jsonb_build_object(
    'id', v_order_id,
    'total', v_total,
    'items', (
      select jsonb_agg(jsonb_build_object(
        'name', item_name,
        'price', unit_price,
        'quantity', quantity,
        'serving_note', serving_note
      ) order by id)
      from public.order_items
      where order_id = v_order_id
    )
  );
end;
$$;

